let _geo = null;
/** World countries and US states as TopoJSON, with topojson-client: about
 *  220 KB, fetched only when a map is drawn. */
export function loadGeo() {
  if (!_geo) {
    _geo = Promise.all([
      import("world-atlas/countries-110m.json"),
      import("us-atlas/states-10m.json"),
      import("topojson-client"),
    ]).then(([world, us, topojson]) => ({ world: world.default || world, us: us.default || us, topojson }));
  }
  return _geo;
}
