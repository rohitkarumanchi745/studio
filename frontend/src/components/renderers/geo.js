/** "Côte d'Ivoire" / "cote divoire" / "COTE D’IVOIRE" → one key. */
export function placeKey(s) {
  return String(s ?? "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
    .replace(/['’.]/g, "").replace(/&/g, " and ").replace(/[^a-z0-9]+/g, " ").trim()
    .replace(/^the /, "");
}

/** name/code → id; a key two places share is dropped, not guessed — unless
 *  `settled` says which place it is. Exported for tests. */
export function indexOf(entries, settled = []) {
  const out = new Map(), clash = new Set();
  for (const [id, ...names] of entries) {
    for (const n of [id, ...names]) {
      const k = placeKey(n);
      if (!k) continue;
      if (out.has(k) && out.get(k) !== id) clash.add(k);
      else out.set(k, id);
    }
  }
  for (const k of clash) out.delete(k);
  for (const [id, name] of settled) out.set(placeKey(name), id);
  return out;
}

// world-atlas gives three features no ISO number: they are keyed by name
// (Kosovo's user-assigned code, 983, is not on the map).
const UNNUMBERED = [["name:Kosovo", "XK", "XKK", "XKX", "Kosovo"], ["name:Somaliland", "Somaliland"],
                    ["name:N. Cyprus", "Northern Cyprus", "N. Cyprus"]];
// Where a name is shared, ISO 3166's own short name decides: "Congo" is the
// Republic of the Congo; the other is "Congo, Democratic Republic of the".
const ISO_SHORT = [["178", "Congo"]];
const PLACES = {
  world: { index: indexOf([...COUNTRIES.filter((c) => c[1] !== "XK"), ...UNNUMBERED], ISO_SHORT),
           hint: /country|countries|nation/ },
  us: { index: indexOf(US_STATES.map(([fips, code, name]) => [fips, code, name, String(Number(fips))])),
        hint: /state/ },
};

/** The id world-atlas / us-atlas gives a feature. */
export function featureKey(f) {
  return f.id !== undefined && f.id !== null ? String(f.id) : `name:${f.properties?.name}`;
}

/**
 * Whether column `i` names countries or US states, and how each value
 * resolves: {kind: "world" | "us", ids: Map(value → id), unmatched: [values]}.
 * Most of its distinct values must match; the column's name breaks a tie
 * ("CA" is California and Canada). Exported for tests.
 */
export function placeColumn(columns, rows, i) {
  if (i < 0) return null;
  // Places are written as text: a column of numbers (ids, counts) is not one,
  // however many happen to look like FIPS codes.
  if (typeof rows.find((r) => r[i] !== null && r[i] !== undefined)?.[i] !== "string") return null;
  const values = [...new Set(rows.map((r) => r[i]).filter((v) => v !== null && v !== undefined && v !== ""))];
  if (!values.length) return null;
  const tried = Object.entries(PLACES).map(([kind, { index, hint }]) => {
    const ids = new Map(), unmatched = [];
    for (const v of values) {
      const id = index.get(placeKey(v));
      if (id) ids.set(v, id); else unmatched.push(v);
    }
    return { kind, ids, unmatched, hinted: hint.test(String(columns[i]).toLowerCase()) };
  }).filter((t) => t.ids.size / values.length >= 0.6);
  if (!tried.length) return null;
  tried.sort((a, b) => (b.hinted - a.hinted) || (b.ids.size - a.ids.size)
                       || (a.kind === "world" ? -1 : 1));
  const { kind, ids, unmatched } = tried[0];
  return { kind, ids, unmatched };
}

// ── What each map draws ─────────────────────────────────────────────────

/** A numeric column of the spec's y (not one of `skip`), or -1. */
function valueIndex(columns, rows, spec, skip = []) {
  for (const c of spec?.y || []) {
    const i = columns.indexOf(c);
    if (i >= 0 && !skip.includes(i) && inRange(rows, i, Infinity) && typeof rows[0]?.[i] !== "string") return i;
  }
  return -1;
}

/** The role a column's name gives it: "origin" (from_stop, origin_country),
 *  "dest" (to_stop, destination_country), or null. */
function roleOf(name) {
  const t = tokens(name);
  return t.some((x) => ORIGIN.has(x)) ? "origin" : t.some((x) => DEST.has(x)) ? "dest" : null;
}

/** A text column named for one end of a trip (from_stop / to_stop), or -1. */
function endLabel(columns, rows, role, skip = []) {
  return columns.findIndex((c, i) => !skip.includes(i) && typeof rows[0]?.[i] === "string"
                                     && roleOf(c) === role);
}

/** A column to name a place by: x when it is text, else the first text column. */
function labelIndex(columns, rows, spec, skip = []) {
  const x = columns.indexOf(spec?.x);
  if (x >= 0 && !skip.includes(x) && typeof rows[0]?.[x] === "string") return x;
  return columns.findIndex((_, i) => !skip.includes(i) && typeof rows[0]?.[i] === "string");
}

// The boxes geoAlbersUsa draws: the lower 48, Alaska and Hawaii.
const US_BOXES = [[-125, 24.4, -66.9, 49.4], [-180, 51, -129.9, 71.5], [-161, 18.9, -154.7, 22.3]];
/** Whether every coordinate lies in the US — then the map is the US. */
export function allInUS(coords) {
  return coords.length > 0 && coords.every(([lon, lat]) =>
    US_BOXES.some(([w, s, e, n]) => lon >= w && lon <= e && lat >= s && lat <= n));
}

const at = (r, i) => (i >= 0 ? r[i] : null);
const finite = (lon, lat) => Number.isFinite(lon) && Number.isFinite(lat)
  && Math.abs(lat) <= 90 && Math.abs(lon) <= 180;

/**
 * Routes between places, summed per origin → destination:
 * {kind, routes: [{from: {lon, lat} | {id}, to, fromLabel, toLabel, value}],
 *  measured: whether value is a column (else it counts rows), unmatched}.
 * Exported for tests.
 */
export function routeMapData(columns, rows, spec) {
  const pairs = coordinatePairs(columns, rows);
  const o = pairs.find((p) => p.role === "origin");
  const d = pairs.find((p) => p.role === "dest");
  const sum = new Map();
  let kind, measured, valueName, unmatched = [];
  if (o && d) {
    const coordCols = [o.lat, o.lon, d.lat, d.lon];
    const vi = valueIndex(columns, rows, spec, coordCols);
    // Each end's name: a column named for it (from_stop → to_stop), else
    // x for the origin and y[0] for the destination when they are text.
    let fi = endLabel(columns, rows, "origin", coordCols);
    if (fi < 0) fi = labelIndex(columns, rows, spec, coordCols);
    let ti = endLabel(columns, rows, "dest", [...coordCols, fi]);
    if (ti < 0) {
      const y0 = columns.indexOf(spec?.y?.[0]);
      ti = y0 >= 0 && y0 !== fi && !coordCols.includes(y0) && typeof rows[0]?.[y0] === "string" ? y0 : -1;
    }
    measured = vi >= 0;
    valueName = measured ? columns[vi] : "trips";
    for (const r of rows) {
      const from = [num(r[o.lon]), num(r[o.lat])], to = [num(r[d.lon]), num(r[d.lat])];
      if (!finite(...from) || !finite(...to)) continue;
      if (from[0] === to[0] && from[1] === to[1]) continue;
      const key = [...from, ...to].map((v) => v.toFixed(4)).join(",");
      const v = measured ? num(r[vi]) : 1;
      const hit = sum.get(key) || { from: { lon: from[0], lat: from[1] }, to: { lon: to[0], lat: to[1] },
                                     fromLabel: at(r, fi), toLabel: at(r, ti), value: 0 };
      hit.value += Number.isFinite(v) ? v : 0;
      sum.set(key, hit);
    }
    const coords = [...sum.values()].flatMap((t) => [[t.from.lon, t.from.lat], [t.to.lon, t.to.lat]]);
    kind = allInUS(coords) ? "us" : "world";
  } else {
    // Places by name: x → y[0] when both are places; else the columns named
    // for each end (origin_country → destination_country); else the two
    // place columns there are.
    const places = columns.map((_, i) => placeColumn(columns, rows, i));
    const isPlace = (i) => i >= 0 && !!places[i];
    let fi = columns.indexOf(spec?.x), ti = columns.indexOf(spec?.y?.[0]);
    if (!isPlace(fi) || !isPlace(ti) || fi === ti) {
      const named = (role) => columns.findIndex((c, i) => isPlace(i) && roleOf(c) === role);
      fi = named("origin");
      ti = named("dest");
      if (fi < 0 || ti < 0) {
        const all = columns.map((_, i) => i).filter(isPlace);
        [fi, ti] = all.length === 2 ? all : [-1, -1];
      }
    }
    if (fi < 0 || ti < 0 || fi === ti) return null;
    const from = places[fi], to = places[ti];
    if (from.kind !== to.kind) return null;
    kind = from.kind;
    const vi = valueIndex(columns, rows, spec, [fi, ti]);
    measured = vi >= 0;
    valueName = measured ? columns[vi] : "trips";
    unmatched = [...new Set([...from.unmatched, ...to.unmatched].map(String))];
    for (const r of rows) {
      const a = from.ids.get(r[fi]), b = to.ids.get(r[ti]);
      if (!a || !b || a === b) continue;
      const key = `${a}>${b}`;
      const v = measured ? num(r[vi]) : 1;
      const hit = sum.get(key) || { from: { id: a }, to: { id: b }, fromLabel: r[fi], toLabel: r[ti], value: 0 };
      hit.value += Number.isFinite(v) ? v : 0;
      sum.set(key, hit);
    }
  }
  const routes = [...sum.values()].sort((a, b) => b.value - a.value).slice(0, MAP_LIMITS.routes);
  if (!routes.length) return null;
  return { kind, routes, measured, valueName, unmatched, total: sum.size };
}

/**
 * Places as dots: {kind, points: [{lon, lat} | {id}, label, value}], measured,
 * unmatched}. Coordinates when the result has them, else countries / US
 * states (at their centre). Exported for tests.
 */
export function pointMapData(columns, rows, spec) {
  const pairs = coordinatePairs(columns, rows);
  const p = pairs.find((x) => x.role === "point") || pairs[0];
  if (p) {
    const coordCols = pairs.flatMap((x) => [x.lat, x.lon]);
    const vi = valueIndex(columns, rows, spec, coordCols);
    const li = labelIndex(columns, rows, spec, coordCols);
    const points = [];
    for (const r of rows) {
      const lon = num(r[p.lon]), lat = num(r[p.lat]);
      if (!finite(lon, lat)) continue;
      const v = vi >= 0 ? num(r[vi]) : null;
      points.push({ lon, lat, label: at(r, li), value: Number.isFinite(v) ? v : null });
      if (points.length >= MAP_LIMITS.points) break;
    }
    if (!points.length) return null;
    return { kind: allInUS(points.map((x) => [x.lon, x.lat])) ? "us" : "world", points,
             measured: vi >= 0, valueName: vi >= 0 ? columns[vi] : null, unmatched: [] };
  }
  const regions = choroplethData(columns, rows, spec);
  if (!regions) return null;
  return { kind: regions.kind, points: regions.regions.map((r) => ({ ...r })),
           measured: regions.measured, valueName: regions.valueName, unmatched: regions.unmatched };
}

/**
 * Countries or US states and a value each (summed; with no value column, the
 * number of rows): {kind, regions: [{id, label, value}], measured, unmatched}.
 * Exported for tests.
 */
export function choroplethData(columns, rows, spec) {
  let ri = columns.indexOf(spec?.x);
  let places = placeColumn(columns, rows, ri);
  for (let i = 0; !places && i < columns.length; i++) {
    if (i === ri || typeof rows[0]?.[i] !== "string") continue;
    places = placeColumn(columns, rows, i);
    if (places) ri = i;
  }
  if (!places) return null;
  const vi = valueIndex(columns, rows, spec, [ri]);
  const sum = new Map();
  for (const r of rows) {
    const id = places.ids.get(r[ri]);
    if (!id) continue;
    const v = vi >= 0 ? num(r[vi]) : 1;
    const hit = sum.get(id) || { id, label: r[ri], value: 0 };
    hit.value += Number.isFinite(v) ? v : 0;
    sum.set(id, hit);
  }
  if (!sum.size) return null;
  return { kind: places.kind, regions: [...sum.values()], measured: vi >= 0,
           valueName: vi >= 0 ? columns[vi] : "rows", placeName: columns[ri],
           unmatched: places.unmatched.map(String) };
}

/** What each map draws, by type. */
export const MAP_DATA = { route_map: routeMapData, point_map: pointMapData, choropleth: choroplethData };

