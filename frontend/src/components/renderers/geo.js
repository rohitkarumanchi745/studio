// Maps for the D3 engine: which columns of a result are places, and where
// they are. Pure — rows in, plain objects out — so what a map will draw is
// tested without a DOM, and ChartView can say whether a map fits.
//
// Three maps:
//   route_map   movement between places — transit, shipments, trips, flights:
//               origin → destination, drawn as great-circle routes sized by
//               volume. Places are coordinate pairs (from_lat/from_lon →
//               to_lat/to_lon, pickup_latitude → dropoff_latitude…) or names
//               of countries / US states (x origin, y = [destination, value]).
//   point_map   places as dots sized by a value: a latitude/longitude pair
//               (stop_lat/stop_lon, latitude/longitude…), or countries / US
//               states at their centre (x the place, y = [value]).
//   choropleth  countries or US states shaded by a value (x the place,
//               y = [value]); with no value, by how many rows each has.
//
// Places are matched offline: ISO codes and names for countries
// (geo-countries.json, generated by scripts/gen_geo_countries.py) and USPS
// codes, FIPS codes and names for US states. Nothing is geocoded over the
// network, so a city name alone is not a place — it needs its coordinates.
import COUNTRIES from "./geo-countries.json";

export const MAP_TYPES = new Set(["route_map", "point_map", "choropleth"]);
export const MAP_LIMITS = { points: 5000, routes: 2000 };

// ── Column names ────────────────────────────────────────────────────────

const LAT = new Set(["lat", "latitude"]);
const LON = new Set(["lon", "lng", "long", "longitude"]);
const ORIGIN = new Set(["origin", "orig", "from", "src", "source", "start", "pickup", "departure",
                        "depart", "dep", "o"]);
const DEST = new Set(["dest", "destination", "to", "dst", "target", "end", "dropoff", "arrival",
                      "arr", "d"]);

/** "PickupLatitude" / "pickup-latitude" → ["pickup", "latitude"]. */
export function tokens(name) {
  return String(name ?? "").replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase()
    .split(/[^a-z0-9]+/).filter(Boolean);
}

const num = (v) => (typeof v === "number" ? v : v === null || v === "" ? NaN : Number(v));

/** Whether most of a column's values are numbers within ±limit. */
function inRange(rows, i, limit) {
  let seen = 0, good = 0;
  for (const r of rows) {
    const v = r[i];
    if (v === null || v === undefined || v === "") continue;
    seen++;
    const n = num(v);
    if (Number.isFinite(n) && Math.abs(n) <= limit) good++;
  }
  return seen > 0 && good / seen >= 0.9;
}

/**
 * The coordinate columns of a result, paired by name: `from_lat` with
 * `from_lon`, `pickup_latitude` with `pickup_longitude`. Each pair's role is
 * where the trip begins ("origin"), ends ("dest"), or neither ("point").
 * Values must be plausible degrees. Exported for tests.
 */
export function coordinatePairs(columns, rows) {
  const lats = new Map(), lons = new Map();
  columns.forEach((c, i) => {
    const t = tokens(c);
    const ll = t.findIndex((x) => LAT.has(x) || LON.has(x));
    if (ll < 0) return;
    const rest = t.filter((_, j) => j !== ll).join("_");
    (LAT.has(t[ll]) ? lats : lons).set(rest, i);
  });
  const out = [];
  for (const [key, lat] of lats) {
    const lon = lons.get(key);
    if (lon === undefined || !inRange(rows, lat, 90) || !inRange(rows, lon, 180)) continue;
    const t = key ? key.split("_") : [];
    const role = t.some((x) => ORIGIN.has(x)) ? "origin" : t.some((x) => DEST.has(x)) ? "dest" : "point";
    out.push({ key, role, lat, lon });
  }
  return out;
}

